"""Dynamic Team Generator — creates engineering roles from a TaskDAG.

Agent roles are generated by an LLM that reads the actual task nodes,
user intent, and repo profile. This produces roles tailored to the specific
request rather than a fixed set of templates.

Fallback: if LLM is unavailable, _generate_fixed_team() maps capabilities
to the original 11-role template set.
"""
from __future__ import annotations

import json
import re
from dataclasses import dataclass, field
from typing import Dict, List, Optional

from agent.orchestration.task_dag import TaskDAG, TaskNode


@dataclass
class OwnedScope:
    """Resources an agent exclusively owns during execution."""
    files: List[str] = field(default_factory=list)
    symbols: List[str] = field(default_factory=list)
    directories: List[str] = field(default_factory=list)
    ports: List[int] = field(default_factory=list)


@dataclass
class AgentRole:
    id: str
    role: str
    mission: str
    owns: OwnedScope = field(default_factory=OwnedScope)
    task_node_ids: List[str] = field(default_factory=list)
    dependencies: List[str] = field(default_factory=list)
    validation_rules: List[str] = field(default_factory=list)
    recovery_rules: List[str] = field(default_factory=list)
    tools: List[str] = field(default_factory=list)
    max_turns: int = 80


@dataclass
class TeamPlan:
    agents: List[AgentRole]
    complexity: float
    risk_assessment: str
    estimated_total_turns: int
    estimated_total_tokens: int
    parallel_benefit: float
    parallel_cost: float
    recommended_strategy: str
    reasoning: str
    layer_count: int = 1


