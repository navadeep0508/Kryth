def generate_team(dag: TaskDAG, user_input: str = "", repo_profile=None) -> TeamPlan:
    """Generate an engineering team from a TaskDAG.

    Uses LLM to create task-specific agent roles. Falls back to the fixed
    capability→role mapping when LLM is unavailable.
    """
    layers = dag.layers()

    # Build compact repo summary
    repo_summary = ""
    if repo_profile is not None:
        try:
            parts = []
            if getattr(repo_profile, "languages", []):
                parts.append(f"Languages: {', '.join(repo_profile.languages[:3])}")
            if getattr(repo_profile, "frameworks", []):
                parts.append(f"Frameworks: {', '.join(repo_profile.frameworks[:4])}")
            repo_summary = "; ".join(parts)
        except Exception:
            pass

    agents: list[AgentRole] = []

    if user_input:
        raw = _llm_generate_team(dag, user_input, repo_summary)
        if raw:
            parsed = _parse_llm_agents(raw, dag)
            if parsed:
                agents = parsed

    if not agents:
        agents = _generate_fixed_team(dag, layers)

    # Force all agents into Layer 1: strip every inter-agent dependency so all
    # 4 agents start simultaneously. Agents read any files they need from disk;
    # the integrator resolves any ordering concerns at the end.
    for a in agents:
        a.dependencies = []

    # Compute complexity and strategy
    total_turns = dag.total_estimated_turns()
    num_agents = len(agents)
    complexity = min(10.0, total_turns / 50 + num_agents * 0.5)
    parallel_benefit = _compute_parallel_benefit(dag, num_agents)
    parallel_cost = _compute_parallel_cost(dag, num_agents)

    dag_layers = dag.layers()

    if num_agents <= 1:
        strategy = "single"
        reasoning = "Single agent sufficient"
    else:
        # Parallel-first: always use parallel for 2+ agents.
        # The scheduler enforces real dependency ordering via agent layers —
        # "parallel" just means we use ThreadPoolExecutor within each layer.
        # For a fully linear DAG every layer has 1 agent, so parallel adds no
        # overhead but costs nothing either.
        strategy = "parallel"
        reasoning = (
            f"Parallel-first: {num_agents} agents, {len(dag_layers)} layers, "
            f"{parallel_benefit:.1f}x theoretical speedup"
        )

    risk_counts = dag.risk_summary()
    risk_str = ", ".join(f"{k}={v}" for k, v in sorted(risk_counts.items()))

    return TeamPlan(
        agents=agents,
        complexity=round(complexity, 1),
        risk_assessment=risk_str,
        estimated_total_turns=total_turns,
        estimated_total_tokens=total_turns * 2000,
        parallel_benefit=round(parallel_benefit, 2),
        parallel_cost=round(parallel_cost, 2),
        recommended_strategy=strategy,
        reasoning=reasoning,
        layer_count=len(layers),
    )


