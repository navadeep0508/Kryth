def _llm_generate_team(
    dag: TaskDAG,
    user_input: str,
    repo_summary: str,
) -> Optional[List[dict]]:
    """Ask the planner model to generate a dynamic team. Returns raw agent dicts or None."""
    try:
        from agent.llm import _get_client, PLANNER_MODEL

        dag_summary = json.dumps([
            {"id": n.id, "name": n.name, "description": n.description,
             "capabilities": n.capabilities_required,
             "dirs": n.affected_dirs, "files": n.affected_files[:4]}
            for n in dag.nodes.values()
        ], separators=(",", ":"))

        prompt = (
            f"Task: {user_input[:800]}\n\n"
            f"Repository context: {repo_summary[:800]}\n\n"
            f"Work items: {dag_summary[:1500]}\n\n"
            "Generate the 4-agent parallel team:"
        )
        try:
            from agent.model_router import TaskRole, pick_model_for_role
            _team_model = pick_model_for_role(TaskRole.PLANNING)
        except Exception:
            _team_model = PLANNER_MODEL
        client = _get_client()
        resp = client.chat.completions.create(
            model=_team_model,
            messages=[
                {"role": "system", "content": _TEAM_SYSTEM},
                {"role": "user", "content": prompt},
            ],
            temperature=0,
            max_tokens=2000,
            timeout=10,
        )
        raw = (resp.choices[0].message.content or "").strip()
        raw = re.sub(r"^```[a-z]*\n?", "", raw).rstrip("`").strip()
        start = raw.find("[")
        end = raw.rfind("]")
        if start < 0 or end <= start:
            return None
        agents = json.loads(raw[start:end + 1])
        if isinstance(agents, list) and agents:
            return agents
    except Exception:
        pass
    return None


def _parse_llm_agents(raw_agents: List[dict], dag: TaskDAG) -> Optional[List[AgentRole]]:
    """Validate and convert raw LLM agent dicts to AgentRole objects."""
    known_node_ids = set(dag.nodes.keys())
    seen_ids: set = set()
    roles: list[AgentRole] = []

    for raw in raw_agents[:4]:
        aid = str(raw.get("id", "")).strip().replace(" ", "-")
        if not aid or aid in seen_ids:
            continue
        seen_ids.add(aid)

        try:
            turns = max(15, min(120, int(raw.get("max_turns", 60))))
        except (TypeError, ValueError):
            turns = 60

        task_ids = [t for t in (raw.get("task_node_ids") or []) if t in known_node_ids]
        deps = [str(d).strip() for d in (raw.get("depends_on") or []) if str(d).strip()]

        owned = OwnedScope(
            directories=list(raw.get("owned_dirs") or []),
            files=list(raw.get("owned_files") or []),
        )

        # Inherit validation/recovery from owned task nodes
        validation: list[str] = []
        recovery: list[str] = []
        for nid in task_ids:
            node = dag.nodes.get(nid)
            if node:
                validation.extend(node.validation)
                if node.rollback_strategy:
                    recovery.append(node.rollback_strategy)

        roles.append(AgentRole(
            id=aid,
            role=str(raw.get("role", aid)),
            mission=str(raw.get("mission", f"Complete {aid} tasks")),
            owns=owned,
            task_node_ids=task_ids,
            dependencies=deps,
            validation_rules=validation,
            recovery_rules=recovery,
            max_turns=turns,
        ))

    if not roles:
        return None

    # Validate deps reference known agent ids
    valid_aids = {r.id for r in roles}
    for r in roles:
        r.dependencies = [d for d in r.dependencies if d in valid_aids]

    return roles


