def _find_role(node: TaskNode) -> str:
    for cap in node.capabilities_required:
        role = _CAP_TO_ROLE.get(cap)
        if role:
            return role
    return "backend specialist"


def _generate_fixed_team(dag: TaskDAG, layers: list) -> list[AgentRole]:
    """Original fixed capability→role mapping used as fallback."""
    agent_map: Dict[str, AgentRole] = {}
    node_owners: Dict[str, str] = {}

    for layer in layers:
        for node in layer:
            role = _find_role(node)
            agent_id = role.lower().replace(" ", "_")
            if agent_id not in agent_map:
                template = _ROLE_TEMPLATES.get(role, {"mission": f"Complete all {role} work", "tools": [], "max_turns": 60})
                agent_map[agent_id] = AgentRole(
                    id=agent_id, role=role,
                    mission=template["mission"],
                    tools=template["tools"],
                    max_turns=template["max_turns"],
                )
            agent = agent_map[agent_id]
            agent.task_node_ids.append(node.id)
            agent.owns.files.extend(node.affected_files)
            agent.owns.symbols.extend(node.affected_symbols)
            agent.owns.directories.extend(node.affected_dirs)
            agent.validation_rules.extend(node.validation)
            if node.rollback_strategy:
                agent.recovery_rules.append(node.rollback_strategy)
            node_owners[node.id] = agent_id

    # Build agent dependency graph from node dependencies, but ONLY add a
    # dependency when the upstream agent's OUTPUT is actually needed (i.e.
    # the upstream produces schema/contracts the downstream consumes).
    # Avoid chaining agents that could run in parallel (e.g. auth + backend
    # both need the database, but they don't depend on each other).
    for agent in agent_map.values():
        direct_upstream_roles: set = set()
        for nid in agent.task_node_ids:
            node = dag.nodes.get(nid)
            if node:
                for dep_nid in node.dependencies:
                    owner = node_owners.get(dep_nid)
                    owner_agent = agent_map.get(owner) if owner else None
                    if owner and owner != agent.id and owner_agent:
                        # Only add dependency if the upstream agent owns FOUNDATION
                        # work (database/schema/auth) that this agent literally needs
                        # to exist before it can start. Skip cross-cutting deps like
                        # testing→backend or devops→testing (they share no live data).
                        upstream_role = owner_agent.role.lower()
                        is_foundation = any(k in upstream_role for k in
                                            ("database", "schema", "auth", "migration"))
                        if is_foundation:
                            direct_upstream_roles.add(owner)
        agent.dependencies = sorted(direct_upstream_roles)

    return list(agent_map.values())


def _compute_parallel_benefit(dag: TaskDAG, num_agents: int) -> float:
    layers = dag.layers()
    if len(layers) <= 1:
        return 1.0
    sequential = dag.total_estimated_turns()
    # Parallel time = sum of max-turns per layer (nodes within a layer run concurrently).
    # BUG FIX: was using sum() which pessimistically adds all node turns in a layer.
    total_parallel_time = sum(
        max(n.estimated_turns for n in layer)
        for layer in layers
    )
    speedup = sequential / max(total_parallel_time, 1)
    # Light coordination penalty: 2% per agent (not 5% — agents share state via outputs)
    coordination = max(0.0, 1.0 - 0.02 * num_agents)
    return speedup * coordination


def _compute_parallel_cost(dag: TaskDAG, num_agents: int) -> float:
    if num_agents <= 1:
        return 1.0
    # Per-agent overhead: context transfer (10%) + result merge (15%) + startup (8%)
    # No quadratic coordination term — agents share state via prior_outputs, not P2P.
    per_agent = 0.10 + 0.15 + 0.08   # = 0.33 per agent
    return 1.0 + per_agent * num_agents * 0.5  # dampened: 5 agents → ~1.83x
